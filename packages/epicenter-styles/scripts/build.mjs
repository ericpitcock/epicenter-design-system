// ---------------------------------------------------------------------------
// Theme seeds (tokens/theme.yaml → _seeds.scss, @property preamble, theme.css)
// ---------------------------------------------------------------------------

/** Flat list of every seed, in file order, with its group attached. */
function loadSeeds() {
  const groups = readYAML(join(tokensDir, 'theme.yaml'))
  const seeds = []
  for (const group of groups) {
    for (const [name, seed] of Object.entries(group.seeds)) {
      seeds.push({ name: `--${name}`, group: group.group, ...seed })
    }
  }
  return { groups, seeds }
}

/**
 * The @property rules for every registered seed.
 *
 * Registration means a consumer's bad value (`--primary-color: #gg0000`) falls
 * back to the initial value instead of making every `oklch(from var(--primary-
 * color) …)` invalid at computed-value time — which would blank roughly a third
 * of the component layer. It also makes a `<color>` seed compute to a resolved
 * color, so a derivation from --accent-color does not textually nest two
 * relative-color functions.
 */
function propertyPreamble(seeds) {
  const rules = []
  for (const seed of seeds) {
    if (!seed.property) continue
    const initial = seed.initial ?? seed.value
    // The spec requires a computationally independent initial-value; a var()
    // there registers nothing, silently.
    if (/var\(/.test(initial)) {
      throw new Error(
        `theme.yaml: ${seed.name} is registered but its initial-value "${initial}" ` +
        'contains var(). Give it a literal `initial`.'
      )
    }
    rules.push(`@property ${seed.name}{syntax:"${seed.property}";inherits:true;initial-value:${initial}}`)
  }
  return rules.join('')
}

const wrapComment = (text, indent = '  ') =>
  text
    .trim()
    .split('\n')
    .map(line => `${indent} * ${line}`.replace(/\s+$/, ''))
    .join('\n')

/** The starter file a consumer copies. Every value is the shipped default. */
function themeStarter(groups, chartSequence) {
  let out = `/* Epicenter theme
 *
 * Copy this file into your app, edit the values, and load it AFTER the package
 * stylesheet:
 *
 *   import '@ericpitcock/epicenter-styles'
 *   import './theme.css'
 *
 * It is deliberately unlayered, so every line here beats the package defaults
 * regardless of specificity — no !important, no out-specifying selectors.
 *
 * Every value below is the shipped default; delete anything you do not change.
 * Colors may be written in any color space (hex, hsl, oklch, named): the
 * ramps derive with oklch(from …), which converts the origin first.
 *
 * Light and dark are not separate themes. Every derived token is a light-dark()
 * pair driven by color-scheme, so one set of seeds covers both modes.
 *
 * Generated by scripts/build.mjs from tokens/theme.yaml. Regenerate, do not edit.
 */
:root {
`

  for (const group of groups) {
    out += `  /* ---- ${group.group} ${'-'.repeat(Math.max(3, 66 - group.group.length))}\n`
    if (group.intro) out += `${wrapComment(group.intro)}\n`
    out += '   */\n'
    for (const [name, seed] of Object.entries(group.seeds)) {
      if (seed.comment) out += `  /*\n${wrapComment(seed.comment)}\n   */\n`
      out += `  --${name}: ${seed.value};\n`
    }
    out += '\n'
  }

  out += `  /* ---- Charts ${'-'.repeat(60)}
 * Series colors, in order. Highcharts reads them through --highcharts-color-N
 * and EpDonutChart indexes its arcs the same way. Two-argument light-dark()
 * entries differ per mode; single-value entries are the same in both.
 * --chart-sequence-count is derived from this list and is not a seed.
   */
`
  for (const [name, value] of Object.entries(chartSequence)) {
    const dark = value.dark ?? value.light
    const light = value.light ?? value.dark
    out += `  --${name}: light-dark(${light}, ${dark});\n`
  }

  out += `}

/* Not here on purpose: the density scales — --space--*, --control-height--*,
 * --font-size--*, --z-index--*, --shadow--*, --duration--*. They are global
 * tokens like any other and can be overridden the same way, but they are not
 * part of a brand theme. */
`
  return out
}

function buildThemeSeeds() {
  console.log('🌱 Building theme seeds...')
  const { groups, seeds } = loadSeeds()

  let scss = `/* stylelint-disable */\n/* DO NOT EDIT DIRECTLY — generated from tokens/theme.yaml */\n:root {\n`
  for (const seed of seeds) scss += `  ${seed.name}: ${seed.value};\n`
  scss += '}\n'
  fs.writeFileSync(seedsSCSS, scss)
  console.log(`  SCSS file generated: ${seedsSCSS}`)

  const preamble = propertyPreamble(seeds)

  const chartSequence = readYAML(join(tokensDir, 'color/chart-sequence.yaml'))
  const starter = themeStarter(groups, chartSequence)
  fs.mkdirSync(distDir, { recursive: true })
  fs.writeFileSync(distThemeCSS, starter)
  if (fs.existsSync(staticDir)) fs.writeFileSync(join(staticDir, 'theme.css'), starter)
  console.log(`  Theme starter generated: ${distThemeCSS}`)

  console.log('✅ Theme seeds built')
  return { seedNames: new Set(seeds.map(seed => seed.name)), preamble }
}

